#!/usr/bin/env python3
"""
Builds the warm, cool and black-and-white versions of every photo.

  1. Convert the photo to black and white (Rec. 601 luma, same as most photo editors).
  2. For warm and cool, put a solid color layer on top with the "Screen" blend mode:
         out = alpha * (1 - (1 - gray) * (1 - mask)) + (1 - alpha) * gray
     warm mask = #ff0000, cool mask = #001eff. alpha is the layer opacity.
  3. Save images/print_NN_warm.jpg, _cool.jpg, _bw.jpg and write images/stats.js with each
     version's colorimetric warmth and luminance (for use as covariates in the analysis).

Source photos live in images/source/print_NN.jpg. Re-run after changing the masks or opacity:
    python3 tools/make_treatments.py --opacity 0.6
"""
import argparse, glob, json, os
import numpy as np
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument('--opacity', type=float, default=0.6, help='Screen layer opacity, 0 to 1 (1 = full strength)')
ap.add_argument('--warm', default='#ff0000')
ap.add_argument('--cool', default='#001eff')
ap.add_argument('--size', type=int, default=400)
args = ap.parse_args()

def hex2rgb(h): h = h.lstrip('#'); return np.array([int(h[i:i+2], 16) for i in (0, 2, 4)]) / 255.0

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir, out_dir = os.path.join(root, 'images', 'source'), os.path.join(root, 'images')
masks = {'warm': hex2rgb(args.warm), 'cool': hex2rgb(args.cool), 'bw': None}
stats = {}

for path in sorted(glob.glob(os.path.join(src_dir, 'print_*.jpg'))):
    pid = os.path.basename(path)[6:8]
    im = Image.open(path).convert('RGB').resize((args.size, args.size), Image.LANCZOS)
    a = np.asarray(im).astype(float) / 255
    matte = (a >= 245 / 255).all(axis=2)                      # white matte pixels are ignored in the stats
    g = 0.299 * a[..., 0] + 0.587 * a[..., 1] + 0.114 * a[..., 2]
    stats[pid] = {}
    for name, m in masks.items():
        if m is None:
            out = np.stack([g, g, g], -1)
        else:
            screen = 1 - (1 - g[..., None]) * (1 - m)
            out = args.opacity * screen + (1 - args.opacity) * g[..., None]
        out8 = (out * 255).round().astype('uint8')
        Image.fromarray(out8).save(os.path.join(out_dir, f'print_{pid}_{name}.jpg'), quality=82, optimize=True)
        px = out8[~matte].astype(float) / 255
        stats[pid][name] = {
            'warmth': round(float(px[:, 0].mean() - px[:, 2].mean()), 4),   # mean R minus mean B
            'luma': round(float((0.2126 * px[:, 0] + 0.7152 * px[:, 1] + 0.0722 * px[:, 2]).mean()), 4),
        }

with open(os.path.join(out_dir, 'stats.js'), 'w') as f:
    f.write('// Generated by tools/make_treatments.py (opacity %s, warm %s, cool %s)\n' % (args.opacity, args.warm, args.cool))
    f.write('const IMAGE_STATS = ' + json.dumps(stats) + ';\n')
    f.write('const TREATMENT_INFO = ' + json.dumps({'opacity': args.opacity, 'warm': args.warm, 'cool': args.cool}) + ';\n')
print(len(stats), 'photos processed')
